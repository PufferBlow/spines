// Derives the files that are computed from the sources, so nothing in them is typed twice:
//
//   tokens/tokens.css   from tokens/theme.css   (the Tailwind theme is the source; this is plain :root for everyone else)
//   tokens/tokens.json  from tokens/theme.css   (every custom property, grouped by kind)
//   cli/marks.json      from cli/glyphs/*.txt   (the terminal marks as rows of text, for any language)
//   manifest.json       from assets/            (what the repo ships, by name, so others do not list directories)
//
//   node scripts/build.mjs                       write them
//   node scripts/build.mjs --check               fail if any is out of date (CI)
//   node scripts/build.mjs --python-out <file>   also write the marks as a Python module (the backend's CLI splash)

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const pythonOut = args.includes("--python-out") ? args[args.indexOf("--python-out") + 1] : null;

const read = (rel) => readFileSync(join(root, rel), "utf8");
const walk = (dir) =>
  readdirSync(join(root, dir), { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(`${dir}/${e.name}`) : [`${dir}/${e.name}`],
  );

/** The contents of the brace-balanced block that starts at `opener` (for example "@theme {"). */
function blockOf(text, opener) {
  const start = text.indexOf(opener);
  if (start === -1) throw new Error(`${opener} not found`);
  let depth = 0;
  for (let i = text.indexOf("{", start); i < text.length; i += 1) {
    if (text[i] === "{") depth += 1;
    if (text[i] === "}" && --depth === 0) return text.slice(text.indexOf("{", start) + 1, i).replace(/^\n+|\s+$/g, "");
  }
  throw new Error(`${opener} is not closed`);
}

const HEADER = "/* Pufferblow brand. This file is the source; the client and the website import it. */\n";
const outputs = new Map();

// ---- tokens
const theme = read("tokens/theme.css");
const themeInner = blockOf(theme, "@theme {");
const rootInner = blockOf(theme, ":root {");
outputs.set("tokens/tokens.css", `${HEADER}:root {\n${themeInner}\n\n${rootInner}\n}\n`);

const groups = { color: {}, radius: {}, shadow: {}, font: {}, motion: {}, pb: {}, other: {} };
for (const [, name, value] of `${themeInner}\n${rootInner}`.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
  const kind = name.slice(2).split("-")[0];
  groups[kind in groups ? kind : "other"][name] = value.trim().replace(/\s+/g, " ");
}
outputs.set("tokens/tokens.json", `${JSON.stringify(groups, null, 2)}\n`);

// ---- terminal marks
const marks = {};
for (const file of walk("cli/glyphs").filter((f) => f.endsWith(".txt")).sort()) {
  const m = /pufferblow-(ascii|braille|half)-(\d+)\.txt$/.exec(file);
  if (!m) continue;
  const rows = read(file).split("\n").map((r) => r.trimEnd());
  while (rows.length && !rows[rows.length - 1]) rows.pop();
  marks[`${m[1]}-${m[2]}`] = rows;
}
outputs.set("cli/marks.json", `${JSON.stringify(marks, null, 2)}\n`);

function pythonModule() {
  const order = ["half-40", "half-26", "half-16", "braille-24", "braille-12", "braille-8", "ascii-40", "ascii-24"];
  const lines = [
    `"""The Pufferblow mark as text, from the brand repo's terminal glyphs (mono marks).`,
    "",
    "Generated by the brand repo (`npm run cli:python`); do not edit. The marks take the terminal's own",
    "foreground colour, with the eyes and mouth left as holes. Keys are (style, width in cells):",
    "",
    "- ``half``: half blocks, two pixels per cell, safe wherever UTF-8 block elements render.",
    "- ``braille``: eight dots per cell, so the small sizes keep their spines and eyes.",
    "- ``ascii``: printable ASCII only, for CI output and terminals that mangle Unicode.",
    '"""',
    "",
    "from __future__ import annotations",
    "",
    "MARKS: dict[tuple[str, int], tuple[str, ...]] = {",
  ];
  for (const key of order) {
    const [style, width] = key.split("-");
    lines.push(`    ('${style}', ${width}): (`);
    for (const row of marks[key]) lines.push(`        ${pyString(row)},`);
    lines.push("    ),");
  }
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

/** A Python string literal the way repr() writes it: single quotes unless the text has one and no double quote. */
function pyString(text) {
  const quote = text.includes("'") && !text.includes('"') ? '"' : "'";
  const escaped = text.replace(/\\/g, "\\\\").replace(new RegExp(quote, "g"), `\\${quote}`);
  return `${quote}${escaped}${quote}`;
}
outputs.set("cli/python/glyph_marks.py", pythonModule());

// ---- manifest
const kb = (rel) => Math.round(statSync(join(root, rel)).size / 102.4) / 10;
const files = (dir, exts) => walk(dir).filter((f) => exts.some((e) => f.endsWith(e))).sort();
const avatarFiles = files("assets/avatars", [".svg"]);
const avatars = {};
for (const file of avatarFiles) {
  const m = /pb-avatar-([a-z]+)-([a-z]+)\.svg$/.exec(file);
  if (m) (avatars[m[1]] ??= {})[m[2]] = file;
}
const manifest = {
  name: "@pufferblow/brand",
  avatars: { expressions: Object.keys(avatars).sort(), tones: [...new Set(Object.values(avatars).flatMap((t) => Object.keys(t)))].sort(), files: avatars },
  patterns: Object.fromEntries(files("assets/patterns", [".svg"]).map((f) => [f.split("/").pop().replace(/-ink\.svg$/, ""), f])),
  logo: Object.fromEntries(
    ["pufferblow-logo", "pufferblow-badge", "pufferblow-mono"].map((set) => [
      set,
      { svg: files(`assets/logo/${set}`, [".svg"]), png: files(`assets/logo/${set}`, [".png"]).length, ...(set === "pufferblow-badge" ? { favicon: "assets/logo/pufferblow-badge/favicon.ico" } : {}) },
    ]),
  ),
  loader: files("assets/loader", [".svg", ".png"]).map((f) => ({ file: f, kb: kb(f) })),
  marks: files("assets/marks", [".svg", ".png"]),
  cli: { glyphs: files("cli/glyphs", [".txt", ".ans"]), json: "cli/marks.json", python: "cli/python/glyph_marks.py" },
  css: files("css", [".css"]),
  tokens: ["tokens/theme.css", "tokens/tokens.css", "tokens/tokens.json"],
  specs: files("specs", [".html"]).filter((f) => !f.includes("/_support/")),
};
outputs.set("manifest.json", `${JSON.stringify(manifest, null, 2)}\n`);

// ---- write or check
let stale = 0;
for (const [rel, text] of outputs) {
  const path = join(root, rel);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === text) continue;
  if (check) {
    stale += 1;
    console.error(`stale: ${rel}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${rel}`);
  }
}
if (pythonOut) {
  writeFileSync(resolve(process.cwd(), pythonOut), outputs.get("cli/python/glyph_marks.py"));
  console.log(`wrote ${relative(process.cwd(), resolve(process.cwd(), pythonOut))}`);
}
if (check && stale) {
  console.error(`${stale} file(s) out of date: run \`npm run build\``);
  process.exit(1);
}
if (check) console.log("derived files are up to date");
